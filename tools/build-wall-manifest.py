#!/usr/bin/env python3
"""Write assets/wall/manifest.js from the per-portrait photo folders."""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
WALL = ROOT / "assets" / "wall"
EXTENSIONS = {".jpg", ".jpeg", ".png", ".webp", ".avif"}


def main() -> None:
    manifest: dict[str, list[str]] = {}
    for index in range(1, 9):
        key = f"{index:02d}"
        folder = WALL / key
        folder.mkdir(parents=True, exist_ok=True)
        files = sorted(
            path for path in folder.iterdir()
            if path.is_file() and path.suffix.lower() in EXTENSIONS
        )
        manifest[key] = [path.relative_to(ROOT).as_posix() for path in files]

    output = WALL / "manifest.js"
    body = json.dumps(manifest, indent=2, ensure_ascii=False)
    output.write_text(
        "// Generated by tools/build-wall-manifest.py. Re-run after adding portrait photos.\n"
        f"window.WUJIANG_WALL = {body};\n",
        encoding="utf-8",
    )
    print(f"Wrote {output.relative_to(ROOT)} with {sum(len(v) for v in manifest.values())} images.")


if __name__ == "__main__":
    main()
