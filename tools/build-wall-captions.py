#!/usr/bin/env python3
"""Write assets/wall/captions.js from per-portrait caption text files."""

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
WALL = ROOT / "assets" / "wall"
SECTION = re.compile(r"^\d{1,2}$")


def parse_captions(path: Path) -> dict[str, str]:
    captions: dict[str, list[str]] = {}
    current: str | None = None
    for raw_line in path.read_text(encoding="utf-8-sig").splitlines():
        line = raw_line.strip()
        if SECTION.fullmatch(line):
            current = f"{int(line):02d}"
            captions.setdefault(current, [])
            continue
        if current is not None and line:
            captions[current].append(line)
    return {number: "\n".join(lines) for number, lines in captions.items() if lines}


def main() -> None:
    manifest: dict[str, dict[str, str]] = {}
    for index in range(1, 9):
        key = f"{index:02d}"
        candidates = (WALL / key / f"{key}captions.txt", WALL / key / f"{key}.txt")
        source = next((path for path in candidates if path.exists()), None)
        manifest[key] = parse_captions(source) if source else {}

    output = WALL / "captions.js"
    body = json.dumps(manifest, indent=2, ensure_ascii=False)
    output.write_text(
        "// Generated by tools/build-wall-captions.py. Re-run after editing caption files.\n"
        f"window.WUJIANG_CAPTIONS = {body};\n",
        encoding="utf-8",
    )
    print(f"Wrote {output.relative_to(ROOT)} with {sum(len(v) for v in manifest.values())} captions.")


if __name__ == "__main__":
    main()
