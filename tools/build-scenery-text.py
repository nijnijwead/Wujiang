#!/usr/bin/env python3
"""Write assets/scenery/stories.js from the per-scenery text files."""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SCENERY = ROOT / "assets" / "scenery"


def read_story(path: Path) -> dict[str, str]:
    if not path.exists():
        return {"title": "", "body": ""}

    lines = path.read_text(encoding="utf-8").replace("\r\n", "\n").split("\n")
    title = ""
    body: list[str] = []

    for line in lines:
        if not title:
            if line.strip():
                title = line.strip()
            continue
        body.append(line)

    return {"title": title, "body": "\n".join(body).strip()}


def main() -> None:
    stories: dict[str, dict[str, str]] = {}
    for index in range(1, 8):
        key = f"{index:02d}"
        zh = read_story(SCENERY / f"{key}.txt")
        en = read_story(SCENERY / f"{key}.en.txt")
        stories[key] = {
            "titleZh": zh["title"],
            "bodyZh": zh["body"],
            "titleEn": en["title"],
            "bodyEn": en["body"],
        }

    output = SCENERY / "stories.js"
    body = json.dumps(stories, indent=2, ensure_ascii=False)
    output.write_text(
        "// Generated by tools/build-scenery-text.py. Re-run after editing the scenery text files.\n"
        f"window.WUJIANG_SCENERY_STORIES = {body};\n",
        encoding="utf-8",
    )
    filled = sum(1 for story in stories.values() if story["bodyZh"])
    print(f"Wrote {output.relative_to(ROOT)} with {filled} Chinese scenery texts.")


if __name__ == "__main__":
    main()
